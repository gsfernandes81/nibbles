"""Where the queue lives, and where this package lives — two different places.

The package is wherever Python found it: a git checkout of nibbles, or
site-packages under a virtual environment once it is installed from PyPI. The
**queue root** is the directory the nightly runner works out of (``queue/``,
``done/``, ``work/``, ``out/``, ``state.json``, ``config.json``), and it must
not move with the package: an item written next to an installed copy would sit
where the runner never looks — queued, apparently fine, and never downloaded.

So the root is ``$EXPIRE_HOME`` when it is set (honoured blindly, so a root can
live anywhere, and :func:`expire_sched.root_problem` says so when it is not
one); else the checkout this package sits in, when it *is* one — it holds the
item contract, ``queue/README.md``; else ``~/nibbles``, which is where the
phone keeps it.

An installed copy makes that last one itself, the first time it runs
(:func:`ensure`). Every root, a checkout included, gets :data:`LAUNCHER` — the
runner the nightly job is armed with, at the path it has always had — and keeps
it pointing at wherever the package is now. Nothing tracked is ever written: in
a checkout the launcher is gitignored, and the contract is never touched.
"""

from __future__ import annotations

import os
from pathlib import Path

#: The package directory, ``nibbles/``.
PACKAGE = Path(__file__).resolve().parent
#: What has to be on ``sys.path`` for ``import nibbles``: the checkout, or the
#: site-packages directory the package was installed into. Queue items and the
#: runner's launcher insert it before they import anything of ours, because
#: they are started by the platform with Termux's own interpreter, which does
#: not know about a virtual environment.
SOURCE = PACKAGE.parent

#: The item contract, which is also what marks a directory as a queue root.
CONTRACT = Path("queue") / "README.md"
#: The contract as the wheel carries it (``pyproject.toml`` force-includes the
#: checkout's ``queue/README.md`` here), for an installed copy to make its root.
SHIPPED_CONTRACT = PACKAGE / "queue-README.md"

#: The runner the job scheduler starts, relative to the root. Its name is the
#: one the job was always armed with, so a phone armed before nibbles was a
#: package keeps firing the same path.
LAUNCHER = "expire_runner.py"
#: The second line of a launcher this module wrote. Only a file carrying it is
#: ever rewritten: anything else at that path is somebody's own.
GENERATED = "# generated by nibbles: the runner the nightly job starts."

#: The runner rejects an item whose interpreter is not on disk, and on Termux
#: /usr/bin/env is not. Written literally rather than from sys.executable so a
#: run under some other interpreter cannot emit an item that will not start.
SHEBANG = "#!/data/data/com.termux/files/usr/bin/python3"


def is_checkout(folder: Path) -> bool:
    """Whether *folder* is a nibbles checkout: the package and the contract."""
    return (folder / CONTRACT).is_file() and (folder / "nibbles" / "__init__.py").is_file()


def root() -> Path:
    """The directory the runner works out of. See the module docstring."""
    override = os.environ.get("EXPIRE_HOME")
    if override:
        return Path(override).expanduser().resolve()
    if (SOURCE / CONTRACT).is_file():
        return SOURCE
    return Path.home() / "nibbles"


def contract() -> str:
    """The item contract's text, from the wheel or from the checkout."""
    for path in (SHIPPED_CONTRACT, SOURCE / CONTRACT):
        if path.is_file():
            return path.read_text(encoding="utf-8")
    return "# The nibbles queue\n\nItems queued by ytq and dlq live here.\n"


def launcher() -> str:
    """The text of the runner launcher for this package, wherever it is."""
    return f'''{SHEBANG}
{GENERATED}
# The code is the nibbles package at the path below; nibbles rewrites this
# file whenever it runs, so an upgrade that moves the package moves this too.
import os
import sys

# The runner works out of the directory it sits in, as it always has.
os.environ["EXPIRE_HOME"] = os.path.dirname(os.path.realpath(__file__))
sys.path.insert(0, {str(SOURCE)!r})

from nibbles.expire_runner import main  # noqa: E402

sys.exit(main())
'''


def ensure(where: Path | None = None) -> list[str]:
    """Make an installed copy's queue root, and keep every root's launcher.

    Returns what was done, one line each, for the command to say; nothing on
    every run after the first. Only ``~/nibbles`` is ever *made*, and only when
    it is missing or empty: a root ``EXPIRE_HOME`` names is theirs to make (and
    ``root_problem`` says what is missing), and a folder of somebody's own is
    never filled with ours. A root that is one — a checkout, ``~/nibbles``, or
    wherever ``EXPIRE_HOME`` points — gets the launcher when it has none, and a
    current one when it holds one of ours that names a package somewhere else.
    """
    where = root() if where is None else where
    said: list[str] = []
    marker = where / CONTRACT
    if not marker.is_file():
        if os.environ.get("EXPIRE_HOME") or (where.exists() and any(where.iterdir())):
            return []
        marker.parent.mkdir(parents=True, exist_ok=True)
        marker.write_text(contract(), encoding="utf-8")
        said.append(f"made the queue at {where}")
    runner = where / LAUNCHER
    wanted = launcher()
    try:
        current = runner.read_text(encoding="utf-8")
    except OSError:
        current = None
    if current is None or (current != wanted and GENERATED in current.splitlines()[:2]):
        runner.write_text(wanted, encoding="utf-8")
        runner.chmod(0o700)
    return said


def child_env() -> dict[str, str]:
    """This environment, with the package first on ``PYTHONPATH``, for a
    ``python -m nibbles`` child: a checkout run with nothing installed is still
    found, and an installed copy's is found first either way."""
    env = dict(os.environ)
    rest = env.get("PYTHONPATH", "")
    env["PYTHONPATH"] = os.pathsep.join(filter(None, (str(SOURCE), rest)))
    return env
